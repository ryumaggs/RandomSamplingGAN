    def top_domination(self, top_n = 5):
        prob_vector = self.generator.test(self.bias_dataset)
        top_values, _ = torch.topk(prob_vector, k=top_n, dim=1)
        top_sum = top_values.sum()
        return top_sum.item()

    def train_generator(self):

        bias_data, _, prob_matrix = self.generator(self.bias_dataset)
        bias_label = self.discriminator(bias_data.to(self.device))
        generator_loss = self.loss_function(bias_label, torch.ones_like(bias_label).to(self.device))
        entropy = self.generator.Shannon_entropy(prob_matrix)
        generator_loss -= 1e-5 * entropy 

        self.generator_optimizer.zero_grad()
        generator_loss.backward()
        self.generator_optimizer.step()

        return generator_loss.item()

    def train_discriminator(self):

        ground_truth_data = self.generate_data()
        ground_truth_label = self.discriminator(ground_truth_data)
        bias_data, _, _ = self.generator(self.bias_dataset)
        bias_label = self.discriminator(bias_data.to(self.device))

        label_pred = torch.cat((ground_truth_label, bias_label), dim=0).to(self.device)
        label_true = torch.cat((torch.ones_like(ground_truth_label), torch.zeros_like(bias_label)), dim=0).to(self.device)
        indices = torch.randperm(label_pred.size(0))
        label_pred = label_pred[indices]
        label_true = label_true[indices]
        discriminator_loss = self.loss_function(label_pred, label_true.to(self.device))

        self.discriminator_optimizer.zero_grad()
        discriminator_loss.backward(retain_graph=True)
        self.discriminator_optimizer.step()

        return discriminator_loss.item()

    def onestep_train(self, generator_training_factor=1, discriminator_training_factor=1):

        generator_losses = []
        discriminator_losses = []
        for _ in range(generator_training_factor):
            generator_loss = self.train_generator()
            generator_losses.append(generator_loss)

        for _ in range(discriminator_training_factor):
            discriminator_loss = self.train_discriminator()
            discriminator_losses.append(discriminator_loss)

        return generator_losses, discriminator_losses

    def train(self):

        #distances = []
        #top5_dominations = []
        predicts = []
        generator_losses, discriminator_losses = [], []

        for epoch in tqdm(range(self.epochs)):
            for i_batch in range(self.batch_in_epoch):
                generator_losses_1ep, discriminator_loss_1ep = self.onestep_train(generator_training_factor=self.generator_training_factor, 
                                                                                  discriminator_training_factor=self.discriminator_training_factor)
            #distance = self.distance2target(5)
            #distances.append(distance)
            #top5_domination = self.top_domination(5)
            #top5_dominations.append(top5_domination)
            generator_losses += generator_losses_1ep
            discriminator_losses += discriminator_loss_1ep

            predicts.append(self.predict(5))

        #return distances, generator_losses, discriminator_losses, top5_dominations
        return generator_losses, discriminator_losses, predicts

    def predict(self, num_batches):
        predicts = []
        for _ in range(num_batches):
            _, indices, _ = self.generator(self.bias_dataset)
            indices = indices.cpu().detach().numpy()
            pred_target = self.label[indices].mean().cpu().detach().item()
            predicts.append(pred_target)
        return np.mean(predicts)        

    def save_gan(self, folder_path):
        torch.save(self.generator.state_dict(), folder_path+"/generator.pt")
        torch.save(self.discriminator.state_dict(), folder_path+"/discriminator.pt")

    def load_gan(self, folder_path):
        self.generator.load_state_dict(torch.load(folder_path+"/generator.pt", weights_only=True))
        self.generator.eval()
        self.discriminator.load_state_dict(torch.load(folder_path+"/discriminator.pt", weights_only=True))
        self.discriminator.eval()

