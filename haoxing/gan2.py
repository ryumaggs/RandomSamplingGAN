class Generator(nn.Module):
    def __init__(self, input_size, bias_size, temperature=0.1):
        super(Generator, self).__init__()
        self.linear = nn.Linear(input_size, 1)
        torch.nn.init.xavier_uniform_(self.linear.weight) 
        #if self.linear.bias is not None:
        #    torch.nn.init.zeros_(self.linear.bias)
        '''
        modules = []
        modules.append(nn.Linear(input_size,256))
        modules.append(nn.LeakyReLU())
        modules.append(nn.Dropout(0.1))
        modules.append(nn.Linear(256,1))
        self.linear = nn.Sequential(*modules)
        for layer_id, layer in enumerate(self.linear):
            #initialize all intermediary layers using relu non linearity
            if isinstance(layer, torch.nn.Linear) and layer_id+1 < len(self.linear):
                if isinstance(self.linear[layer_id+1], torch.nn.LeakyReLU):  # Apply He initialization to Linear layers
                    torch.nn.init.kaiming_uniform_(layer.weight, mode='fan_out', nonlinearity='leaky_relu')  # or kaiming_uniform_
                elif isinstance(self.linear[layer_id+1], torch.nn.Identity):
                    torch.nn.init.xavier_uniform_(layer.weight) 
                if layer.bias is not None:
                    torch.nn.init.zeros_(layer.bias)  # Initialize biases to 0        
        '''
        self.bias_size = bias_size
        self.temperature = temperature

    def forward(self, input):
        logits = None
        logit = self.linear(input).transpose(0,1)
        for _ in range(self.bias_size):
            if logits == None:
                logits = logit
            else:
                logits = torch.cat((logits, logit), dim=0)
        matrix = F.gumbel_softmax(logits, tau=self.temperature, hard=False) # give index
        output = torch.matmul(matrix, input)
        with torch.no_grad():
            max_indices = torch.argmax(matrix, dim=1)
        return output, max_indices, matrix
    
    def generate_samples(self, data, num_samples=5, repeat=False, test_avgs = False):
        input = copy.deepcopy(data)
        outputs, max_indices = None, None
        avgs = []
        logits = self.linear(input).transpose(0,1)
        for _ in range(num_samples):
            matrix = F.gumbel_softmax(logits, tau=self.temperature, hard=False)
            with torch.no_grad():
                max_index = torch.argmax(matrix, dim=1)
                output = input[max_index]
            if outputs == None:
                outputs = output#.unsqueeze(dim=0)
            else:
                outputs = torch.cat((outputs, output), dim = 0)
            if not repeat:
                logits = torch.cat((logits[:, :max_index], logits[:, max_index+1:]), dim = 1) 
                input = torch.cat((input[:max_index], input[max_index+1:]), dim = 0)    
            if test_avgs:
                avg = outputs[:, -1].mean().cpu().detach().item()
                avgs.append(avg)
        if test_avgs:
            return outputs, avgs
        else:
            return outputs

    def test(self, input):
        logit = self.linear(input).transpose(0,1)
        output = nn.Softmax(dim=1)(logit)
        return output
    
    def Shannon_entropy(self, prob_vector):
        epsilon = 1e-10
        return -torch.sum(prob_vector * torch.log(prob_vector + epsilon))

