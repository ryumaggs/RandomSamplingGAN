class GAN():

    def __init__(self, dataset, lr, truth_size, bias_size, temperature, epochs, batch_in_epoch, generator_training_factor, discriminator_training_factor, device):
            
        ground_truth_dataset, bias_dataset = dataset.get_dataset()
        self.ground_truth_dataset = torch.tensor(ground_truth_dataset).to(device)
        self.bias_dataset = torch.tensor(bias_dataset)[:, :-1].to(device)
        self.label = torch.tensor(bias_dataset)[:, -1].to(device)
        #self.real_target = self.ground_truth_dataset[:, -1].mean().cpu().detach().item()

        input_size = dataset.get_dim()
        self.generator = Generator(input_size, bias_size, temperature).to(device)
        self.discriminator = Disctiminator(input_size).to(device)
        self.lr = lr
        self.generator_optimizer = torch.optim.Adam(self.generator.parameters(), lr=self.lr)
        self.discriminator_optimizer = torch.optim.Adam(self.discriminator.parameters(), lr=self.lr)
        self.loss_function = nn.BCEWithLogitsLoss()
        self.truth_size = truth_size
        self.temperature = temperature
        self.epochs = epochs
        self.batch_in_epoch = batch_in_epoch
        self.generator_training_factor = generator_training_factor
        self.discriminator_training_factor = discriminator_training_factor
        self.device = device

    def generate_data(self):
        index = random.sample(range(len(self.ground_truth_dataset)), self.truth_size)
        return self.ground_truth_dataset[index]
    
